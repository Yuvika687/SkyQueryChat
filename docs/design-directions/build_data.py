"""Write shared/data.js for the design mockups from real project data only.

  .venv/bin/python docs/design-directions/build_data.py

Home: each city's latest available PM2.5 24-hour city mean (data/app/city_daily.parquet), its last 7 days and
stations reporting; map positions are the mean coordinates of each city's primary stations (data/app/stations.parquet).
Ask: evaluation answer E01 from evals/runs/20261112-1507_diwali2026_first (a real first-pass answer), plus the
bulletin rows behind its numbers (data/app/city_daily_aqi.parquet) for the proof drawer.
"""
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
APP = ROOT / "data" / "app"
OUT = Path(__file__).resolve().parent / "shared" / "data.js"
CITIES = ["Delhi", "Mumbai", "Kolkata", "Chennai", "Bengaluru", "Hyderabad"]
RUN = ROOT / "evals" / "runs" / "20261112-1507_diwali2026_first" / "results.jsonl"


def home() -> dict:
    d = pd.read_parquet(APP / "city_daily.parquet")
    d["local_date"] = pd.to_datetime(d["local_date"]).dt.date.astype(str)
    pm = d[(d.pollutant == "pm25") & d.meets_rule]
    latest = pm.groupby("city")["local_date"].max()
    end = latest.min()                                    # the latest date every city has
    days = sorted(pm.local_date.unique())
    week = [x for x in days if x <= end][-7:]
    st = pd.read_parquet(APP / "stations.parquet")
    pos = st[st.tier == "primary"].drop_duplicates("location_id").groupby("city")[["lat", "lon"]].mean()
    cities = []
    for c in CITIES:
        x = pm[pm.city == c].set_index("local_date")
        row = x.loc[end]
        cities.append({
            "city": c, "lat": round(float(pos.loc[c, "lat"]), 4), "lon": round(float(pos.loc[c, "lon"]), 4),
            "pm25": round(float(row.city_mean), 1), "stations": int(row.n_valid_stations),
            "stations_total": int(row.n_primary_stations),
            "week": [{"date": w, "pm25": round(float(x.loc[w, "city_mean"]), 1) if w in x.index else None} for w in week]})
    man = json.loads((APP / "manifest.json").read_text())
    return {"latest": end, "week_start": week[0], "cities": cities, "attribution": man.get("attribution", {})}


def ask() -> dict:
    r = next(json.loads(l) for l in RUN.read_text().splitlines() if json.loads(l)["id"] == "E01")
    f = r["final"]
    a = pd.read_parquet(APP / "city_daily_aqi.parquet")
    a["bulletin_date"] = pd.to_datetime(a["bulletin_date"]).dt.date.astype(str)
    fest = a[(a.city == "Delhi") & a.bulletin_date.isin(["2026-11-09", "2026-11-10"])].sort_values("bulletin_date")
    bulletins = [{"date": b.bulletin_date, "aqi": float(b.aqi), "category": b.aqi_category,
                  "pollutant": b.prominent_pollutant, "stations": int(b.no_stations), "stations_total": int(b.total_stations),
                  "from": str(b.period_start_ist)[:16], "to": str(b.period_end_ist)[:16], "source": b.source}
                 for b in fest.itertuples()]
    steps = [{"type": e["type"], "title": e["title"]} for e in r["events"]
             if e["type"] in ("plan", "tool_call", "tool_error", "verification")]
    return {"question": r["question"], "answer": f["answer"], "explanation": f["explanation"],
            "follow_ups": f["follow_ups"], "cards": [{k: c[k] for k in ("label", "value", "unit", "field", "source")}
                                                      for c in f["cards"]],
            "chart": [{"date": p["bulletin_date"], "aqi": p["aqi"], "category": p["category"]}
                      for p in f["chart"]["series"][0]["data"]],
            "required_warnings": [w["text"] for w in f["required_warnings"]],
            "verification": f["verification"], "model": f["model"], "seconds": r["seconds"], "steps": steps,
            "bulletins": bulletins, "run": RUN.parent.name}


if __name__ == "__main__":
    data = {"home": home(), "ask": ask()}
    OUT.write_text("// Generated by build_data.py from data/app and a saved evaluation answer. Do not edit by hand.\n"
                   "window.SQ_DATA = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
    print("wrote", OUT, "latest", data["home"]["latest"])
